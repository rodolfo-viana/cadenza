#!/usr/bin/env python3
"""Builds ui/js/icon-data.js from Lucide icons (https://lucide.dev, ISC).

    npm pack lucide-static && tar xzf lucide-static-*.tgz
    python3 tools/gen_icons.py package/icons

The icon names come from tools/icon-list.txt (one per line).
"""

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit("usage: gen_icons.py <lucide icons dir>")
    icons_dir = pathlib.Path(sys.argv[1])
    if not icons_dir.is_dir():
        sys.exit(f"not a directory: {icons_dir}")
    names = [n.strip() for n in (ROOT / "tools/icon-list.txt").read_text().split() if n.strip()]
    out, missing = {}, []
    for n in names:
        f = icons_dir / f"{n}.svg"
        if not f.exists():
            missing.append(n)
            continue
        inner = re.search(r"<svg[^>]*>(.*)</svg>", f.read_text(), re.S).group(1)
        inner = re.sub(r"<!--.*?-->", "", inner)
        out[n] = re.sub(r"\s+", " ", inner).strip()
    if missing:
        # Writing a partial bundle would leave buttons without glyphs.
        sys.exit(f"missing in {icons_dir}: {' '.join(missing)}\nicon-data.js not written")
    js = ("// Icons from Lucide (https://lucide.dev), ISC License — see vendor/licenses.\n"
          "// Generated by tools/gen_icons.py: each entry is the inner markup of a 24x24 stroke icon.\n"
          "export const ICONS = " + json.dumps(out, indent=0, ensure_ascii=False) + ";\n")
    (ROOT / "ui/js/icon-data.js").write_text(js)
    print(f"{len(out)} icons")


if __name__ == "__main__":
    main()
